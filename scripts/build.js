/* Build client.js from src/ into the single module DSH's loader expects. */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const target = join(root, "client.js");
const MODULE_ID = "dsh-quick-switcher";

const result = await build({
  entryPoints: [join(root, "src/plugin.js")],
  bundle: true,
  format: "cjs",
  platform: "browser",
  target: "es2022",
  charset: "utf8",
  legalComments: "none",
  external: ["react", "@deepseek-ai/dsh-client-ui-primitives"],
  write: false,
});

const body = result.outputFiles[0].text;
const output = `/* Generated by scripts/build.js from src/. Do not edit by hand. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(MODULE_ID)},
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
${body}
    return module.exports.default;
  },
});
`;

if (process.argv.includes("--check")) {
  const normalize = (text) => text.replace(/\r\n/gu, "\n");
  let current;
  try {
    current = readFileSync(target, "utf8");
  } catch (error) {
    // The artifact is not tracked by git, so a fresh clone has no client.js yet.
    // Report that as a missing build rather than letting a bare ENOENT escape.
    if (error.code !== "ENOENT") throw error;
  }
  if (current === undefined) {
    console.error("client.js is missing; run npm run build");
    process.exitCode = 1;
  } else if (normalize(current) !== normalize(output)) {
    console.error("client.js is out of date; run npm run build");
    process.exitCode = 1;
  } else {
    console.log("client.js is up to date");
  }
} else {
  writeFileSync(target, output);
  console.log(`client.js written (${output.length} bytes)`);
}
