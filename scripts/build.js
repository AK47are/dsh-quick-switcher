/* Build the two runtime entries as self-contained files: client.js for DSH's
 * browser module loader and host.js for the host half. The npm package ships
 * only these artifacts plus module.js, so neither entry may import src/. */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const clientTarget = join(root, "client.js");
const hostTarget = join(root, "host.js");
const MODULE_ID = "dsh-quick-switcher";
const BANNER = "/* Generated by scripts/build.js from src/. Do not edit by hand. */\n";

async function bundleClient() {
  const result = await build({
    entryPoints: [join(root, "src/plugin.js")],
    bundle: true,
    format: "cjs",
    platform: "browser",
    target: "es2022",
    charset: "utf8",
    legalComments: "none",
    external: ["react", "@deepseek-ai/dsh-client-ui-primitives"],
    write: false,
  });
  const body = result.outputFiles[0].text;
  return `${BANNER}window.__ModuleLoader__.load({
  id: ${JSON.stringify(MODULE_ID)},
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
${body}
    return module.exports.default;
  },
});
`;
}

async function bundleHost() {
  const result = await build({
    entryPoints: [join(root, "index.js")],
    bundle: true,
    format: "esm",
    platform: "node",
    target: "node20",
    charset: "utf8",
    legalComments: "none",
    write: false,
  });
  return BANNER + result.outputFiles[0].text;
}

const outputs = [
  { path: clientTarget, text: await bundleClient() },
  { path: hostTarget, text: await bundleHost() },
];

if (process.argv.includes("--check")) {
  const normalize = (text) => text.replace(/\r\n/gu, "\n");
  let failed = false;
  for (const output of outputs) {
    const name = output.path.slice(root.length + 1);
    let current;
    try {
      current = readFileSync(output.path, "utf8");
    } catch (error) {
      // The artifacts are not tracked by git, so a fresh clone has neither.
      // Report that as a missing build rather than letting a bare ENOENT escape.
      if (error.code !== "ENOENT") throw error;
    }
    if (current === undefined) {
      console.error(`${name} is missing; run npm run build`);
      failed = true;
    } else if (normalize(current) !== normalize(output.text)) {
      console.error(`${name} is out of date; run npm run build`);
      failed = true;
    } else {
      console.log(`${name} is up to date`);
    }
  }
  if (failed) process.exitCode = 1;
} else {
  for (const output of outputs) {
    writeFileSync(output.path, output.text);
    console.log(`${output.path.slice(root.length + 1)} written (${output.text.length} bytes)`);
  }
}
